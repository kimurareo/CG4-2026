#include "Effect.h"

#include <algorithm>
#include <cstdlib>

using namespace KamataEngine;

// ============================================================
// エフェクトの初期化
// ============================================================
// model      : エフェクトとして表示するモデル
// rotate     : 初期回転角度
// size       : エフェクトの大きさ
// position   : エフェクトを発生させる位置
// color      : エフェクトの色
void Effect::Initialize(Model* model, float rotate, float size, Vector3 position, Vector3 color) {

	// --------------------------------------------------------
	// モデルを保存
	// --------------------------------------------------------
	model_ = model;

	// --------------------------------------------------------
	// ワールド変換を初期化
	// --------------------------------------------------------
	worldTransform_.Initialize();

	// 初期回転
	worldTransform_.rotation_.z = rotate;

	// 初期サイズ
	//
	// Planeモデルを使用しているため、
	// X方向を細く、Y方向をsizeに合わせて設定する。
	worldTransform_.scale_ = {0.1f, size / 2.0f, 1.0f};

	// エフェクトの発生位置
	worldTransform_.translation_ = position;

	// --------------------------------------------------------
	// 色変更用オブジェクトを初期化
	// --------------------------------------------------------
	objectColor_.Initialize();

	// 引数でもらったRGB値を保存
	// Wはアルファ値なので最初は完全に表示する。
	color_ = {color.x, color.y, color.z, 1.0f};

	// --------------------------------------------------------
	// 花火の飛び散る方向をランダムに設定
	// --------------------------------------------------------
	//
	// X方向：
	// -0.1 ～ 0.098程度の範囲で左右に飛び散る
	//
	// Y方向：
	// 0 ～ 0.495程度の上方向へ飛び散る
	//
	// Z方向：
	// 今回は2D的な表現なので移動させない。
	//
	velocity_.x = (rand() % 100 - 50) / 500.0f;
	velocity_.y = (rand() % 100) / 200.0f;
	velocity_.z = 0.0f;

	// --------------------------------------------------------
	// 状態を初期化
	// --------------------------------------------------------

	// 経過時間を0に戻す
	counter_ = 0.0f;

	// エフェクトはまだ終了していない
	isFinished_ = false;

	// --------------------------------------------------------
	// 初期状態のワールド行列を更新
	// --------------------------------------------------------
	//
	// 位置・回転・大きさを設定したので、
	// 実際の描画に反映するために行列を更新する。
	worldTransform_.UpdateMatrix();
}

// ============================================================
// エフェクトの毎フレーム更新
// ============================================================
void Effect::Update() {

	// --------------------------------------------------------
	// すでに終了している場合は更新しない
	// --------------------------------------------------------
	if (isFinished_) {
		return;
	}

	// --------------------------------------------------------
	// 経過時間を進める
	// --------------------------------------------------------
	//
	// 60FPSを想定して、
	// 1フレーム = 1 / 60秒として時間を進める。
	counter_ += 1.0f / 60.0f;

	// --------------------------------------------------------
	// 一定時間経過したらエフェクトを終了
	// --------------------------------------------------------
	if (counter_ >= kDuration) {

		// 時間がkDurationを超えないようにする
		counter_ = kDuration;

		// エフェクト終了
		isFinished_ = true;

		// ----------------------------------------------------
		// 終了したので、これ以降の処理は必要ない。
		// ----------------------------------------------------
		return;
	}

	// ========================================================
	// 回転
	// ========================================================

	// Y軸方向に180度回転
	// Planeモデルの向きを調整する。
	worldTransform_.rotation_.y = 3.14f;

	// Z軸方向に少しずつ回転させる
	// 花火の粒がクルクル回転するような見た目になる。
	worldTransform_.rotation_.z += 0.1f;

	// ========================================================
	// 重力
	// ========================================================

	// 時間が経つにつれてY方向の速度を減少させる。
	//
	// 最初は上方向へ飛ぶ
	// ↓
	// 徐々に速度が遅くなる
	// ↓
	// 最終的には下方向へ落ちる
	velocity_.y -= 0.03f;

	// ========================================================
	// エフェクトを移動
	// ========================================================

	worldTransform_.translation_.x += velocity_.x;
	worldTransform_.translation_.y += velocity_.y;
	worldTransform_.translation_.z += velocity_.z;

	// ========================================================
	// 徐々に透明にする
	// ========================================================

	//
	// counter_ が0
	//     ↓
	// alpha = 1.0（完全に表示）
	//
	// counter_ がkDuration
	//     ↓
	// alpha = 0.0（完全に透明）
	//
	color_.w = std::clamp(1.0f - counter_ / kDuration, 0.0f, 1.0f);

	// 計算した色を描画用オブジェクトへ設定
	objectColor_.SetColor(color_);

	// ========================================================
	// 徐々に大きくする
	// ========================================================

	// X方向を少しずつ拡大
	worldTransform_.scale_.x *= 1.05f;

	// Y方向を少しずつ拡大
	worldTransform_.scale_.y *= 1.07f;

	// ========================================================
	// ワールド行列を更新
	// ========================================================
	worldTransform_.UpdateMatrix();
}

// ============================================================
// エフェクトの描画
// ============================================================
void Effect::Draw(Camera& camera) {

	// --------------------------------------------------------
	// モデルが存在しない場合は描画しない
	// --------------------------------------------------------
	if (model_ == nullptr) {
		return;
	}

	// --------------------------------------------------------
	// エフェクトを描画
	//
	// objectColor_を渡すことで、
	// Update()で設定した色・透明度を反映する。
	// --------------------------------------------------------
	model_->Draw(worldTransform_, camera, &objectColor_);
}